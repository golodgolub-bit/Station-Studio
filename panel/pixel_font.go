func pixelText(dst []byte, text string, top, offset, spacing int, align string, intensity byte) {
	aliases := map[rune]rune{'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X'}
	glyphs := []([]string){}
	width := 0
	for _, r := range strings.ToUpper(text) {
		if a, ok := aliases[r]; ok {
			r = a
		}
		glyph, ok := pixelGlyphs[r]
		if !ok {
			glyph = pixelGlyphs['?']
		}
		rows := strings.Split(glyph, "/")
		glyphs = append(glyphs, rows)
		width += len(rows[0]) + 1 + spacing
	}
	if width > 0 {
		width -= 1 + spacing
	}
	x := 0
	if width <= 25 {
		if align != "left" {
			x = (25 - width) / 2
		}
		if align == "right" {
			x = 25 - width
		}
	} else {
		x = 25 - offset%(width+31)
	}
	for _, rows := range glyphs {
		for y, row := range rows {
			for dx, c := range row {
				xx, yy := x+dx, top+y
				if c == '1' && xx >= 0 && xx < 25 && yy >= 0 && yy < 16 {
					if intensity > dst[yy*25+xx] {
						dst[yy*25+xx] = intensity
					}
				}
			}
		}
		x += len(rows[0]) + 1 + spacing
	}
}
